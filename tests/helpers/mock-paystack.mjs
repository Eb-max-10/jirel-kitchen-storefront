export function isValidPaystackReference(ref) {
  if (typeof ref !== 'string') return false;
  // Standard format generated by Jirel Kitchen: JK_${timestamp}_${random} or general alphanumeric
  return /^JK_\d+_[a-zA-Z0-9]+$/.test(ref) || /^[a-zA-Z0-9_-]{6,64}$/.test(ref);
}
